/**
 * Writes the review pack: every string of a language, grouped by
 * screen, with where it appears, the English, the translation, how wide it may be
 * and where it came from.
 *
 *   node tools/i18n-review-pack.mjs            rewrite docs/translations/review-pack/
 *   node tools/i18n-review-pack.mjs --check    fail if the pack is out of date
 *
 * `--fork <dir>` and `--v2 <dir>` recompute docs/translations/provenance.json from
 * the Korean fork's text and the version 2 dictionaries. Those are not in this
 * repository, so the result is committed and the pack reads it.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = dirname(dirname(fileURLToPath(import.meta.url)));
const args = process.argv.slice(2);
const option = (name) => {
  const at = args.indexOf(`--${name}`);
  return at >= 0 ? args[at + 1] : undefined;
};
const json = (path) => JSON.parse(readFileSync(join(repo, path), 'utf8'));
const LOCALES = json('app/src/i18n/locales.json').filter((locale) => locale.code !== 'en');
const context = json('app/src/i18n/context.json');
const english = json('app/src/i18n/locales/en.json');
const provenancePath = 'docs/translations/provenance.json';

/** The groups these languages read first. */
const STUDIO_GROUPS = ['studio', 'coat', 'variety', 'breed', 'sheep', 'registry', 'angle'];
const STUDIO_FIRST = ['id', 'ms'];

function describeKey(key, prefixes, keys) {
  const prefix = Object.keys(prefixes).filter((candidate) => key.startsWith(candidate)).sort((a, b) => b.length - a.length)[0];
  return [prefix ? prefixes[prefix] : '', keys[key] ?? ''].filter(Boolean).join(' ');
}

function cell(text) {
  return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function table(rows) {
  return ['| Key | Where | English | Translation | Source |', '| --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| \`${row.key}\` | ${cell(row.where)} | ${cell(row.english)} | ${cell(row.translation)} | ${row.source} |`)].join('\n');
}

function renderPack(locale, provenance) {
  const dictionary = json(`app/src/i18n/locales/${locale.code}.json`);
  const sourceOf = (key) => provenance[locale.code]?.[key] ?? 'new';
  const uiRows = Object.keys(english).map((key) => {
    const limit = context.limits[key];
    return {
      key,
      group: key.split('.')[0],
      where: `${describeKey(key, context.prefixes, context.keys)}${limit ? ` Width limit ${limit}.` : ''}`,
      english: english[key],
      translation: dictionary[key],
      source: sourceOf(key),
    };
  });
  const groups = [...new Set(uiRows.map((row) => row.group))]
    .sort((a, b) => Number(STUDIO_GROUPS.includes(b)) - Number(STUDIO_GROUPS.includes(a)));
  const counts = uiRows.reduce((tally, row) => ({ ...tally, [row.source]: (tally[row.source] ?? 0) + 1 }), {});
  const words = uiRows.reduce((sum, row) => sum + row.english.split(/\s+/).length, 0);
  return `# ${locale.nativeName} (\`${locale.code}\`) review pack

**Status: ${locale.reviewed ? 'read by a native speaker' : 'not yet read by a native speaker'}.** Generated by \`tools/i18n-review-pack.mjs\`.
Do not edit this file. Send corrections, or edit \`app/src/i18n/locales/${locale.code}.json\` and regenerate. A native speaker who has read it can also set \`"reviewed": true\` in \`app/src/i18n/locales.json\`.

${uiRows.length} strings, about ${words} English words. By source: ${Object.entries(counts).map(([source, count]) => `${source} ${count}`).join(', ')}.

What the game is: a calm, painterly browser game. You play a sheepdog and guide 25, 75 or 200 sheep through a gate into a pen.

What to check first:

- The Studio, which comes first below. ${STUDIO_FIRST.includes(locale.code) ? 'It should read naturally to a young player, including the coat colours and the Sheep Registry.' : 'It is the screen players most often open first.'}
- The one-line offer: \`offer.prompt\`, \`offer.accept\`, \`offer.decline\`. It is the first thing a new player reads in this language.
- Round touch buttons: \`touch.sprint\`, \`touch.bark\`, \`touch.camera\`. They have width limits.
- The terms for sheep, flock, pen, gate, bark and sprint read naturally and stay the same throughout.
- Nothing should promise it works on a phone. That has not been tested on a real device.
- \`{name}\` holes are filled by the game. Keep them exactly. Word order around them can change.
- The game's prose avoids exclamation marks, hype and emoji.

Source column: \`fork\` is verbatim from the sigco3111/sds Korean fork, \`v2\` is verbatim from the game's earlier dictionary, \`new\` is an unreviewed machine translation made for this release.

${groups.map((group) => `## ${STUDIO_GROUPS.includes(group) ? `Studio: ${group}` : group}\n\n${table(uiRows.filter((row) => row.group === group))}`).join('\n\n')}
`;
}

/** Every string a source file holds, so a translation can be traced by exact match. */
function textFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? textFiles(path) : [path];
  });
}

async function computeProvenance() {
  const flatten = (value, out = []) => {
    for (const item of Object.values(value)) {
      if (typeof item === 'object' && item !== null) flatten(item, out);
      else out.push(String(item));
    }
    return out;
  };
  const provenance = existsSync(join(repo, provenancePath)) ? json(provenancePath) : {};
  const forkDir = option('fork');
  const v2Dir = option('v2');
  const strip = (text) => text.replace(/\{\w+\}/g, '').replace(/\[\[|\]\]/g, '').trim();
  for (const locale of LOCALES) {
    let sourceText = null;
    let label = null;
    if (locale.code === 'ko' && forkDir) {
      sourceText = textFiles(forkDir).map((file) => readFileSync(file, 'utf8')).join('\n');
      label = 'fork';
    } else if (['es', 'pt-BR', 'ja', 'zh-CN'].includes(locale.code) && v2Dir) {
      // Version 2 called Brazilian Portuguese plain `pt`.
      const module = await import(pathToFileURL(join(v2Dir, `${locale.code === 'pt-BR' ? 'pt' : locale.code}.mjs`)).href);
      sourceText = flatten(module.default).join('\n');
      label = 'v2';
    }
    if (sourceText === null) continue;
    const dictionary = json(`app/src/i18n/locales/${locale.code}.json`);
    const matches = {};
    const consider = (key, value) => {
      const bare = strip(value);
      // A two-character label matches anywhere by chance; only a whole line counts then.
      const matched = bare.length >= 6 ? sourceText.includes(bare) : sourceText.split('\n').some((line) => line.trim() === bare);
      if (matched && bare !== '') matches[key] = label;
    };
    for (const [key, value] of Object.entries(dictionary)) consider(key, value);
    provenance[locale.code] = matches;
  }
  return provenance;
}

const provenance = option('fork') || option('v2') ? await computeProvenance() : (existsSync(join(repo, provenancePath)) ? json(provenancePath) : {});
const outDir = join(repo, 'docs/translations/review-pack');
let stale = 0;
if (!args.includes('--check')) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(repo, provenancePath), `${JSON.stringify(provenance, null, 2)}\n`);
}
for (const locale of LOCALES) {
  const path = join(outDir, `${locale.code}.md`);
  const content = renderPack(locale, provenance);
  if (args.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`Stale review pack: ${path}. Run: node tools/i18n-review-pack.mjs`);
      stale += 1;
    }
  } else {
    writeFileSync(path, content);
    console.log(`${path}: ${content.length} bytes`);
  }
}
process.exitCode = stale === 0 ? 0 : 1;
